List<String> _tags(bool isFamily) => [
  for (final filter in KnownFilters(isFamily: isFamily).get())
    for (final option in filter.options) ...[
      if (option.action == FilterAction.list) ...option.actionParams,
      if (option.action2 == FilterAction.list) ...option.action2Params!,
    ],
];

void main() {
  for (final isFamily in [true, false]) {
    test('every list tag exists in the catalog (family: $isFamily)', () {
      final missing = _tags(isFamily).where((t) => !_catalog.contains(t));
      expect(missing, isEmpty);
    });
  }

  test('family safe search enables the unsupported search engines list', () {
    final option = KnownFilters(
      isFamily: true,
    ).get().firstWhere((it) => it.filterName == filterSafeSearch).options.single;
    expect(option.action2Params, contains("safesearch/nosafesearch"));
  });
}
